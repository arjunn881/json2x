export function normalizeCleanPath(pathname: string): string {
  let clean = (pathname || '/').split('?')[0].split('#')[0];
  clean = clean.replace(/\/index\.html$/i, '/');
  clean = clean.replace(/\.html$/i, '');
  clean = clean.replace(/\/+/g, '/');
  if (clean.length > 1) {
    clean = clean.replace(/\/+$/, '');
  }
  return clean || '/';
}

export function isLocalizedRoute(pathname: string): boolean {
  const clean = normalizeCleanPath(pathname);
  return LOCALIZED_STATIC_PATHS.has(clean);
}

